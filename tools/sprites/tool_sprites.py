from PIL import Image
PAL = {
 'sky': {'#': (40, 86, 140), 'o': (110, 190, 245), '+': (210, 245, 255), 'h': (225, 230, 240), 'H': (150, 120, 60)},
 'corrupted': {'#': (30, 12, 40), 'o': (120, 40, 170), '+': (205, 120, 255), 'h': (70, 50, 60), 'H': (40, 26, 34)},
}
import sys
out = sys.argv[1]
for mat, pal in PAL.items():
    for tool, rows in SHAPES.items():
        im = Image.new('RGBA', (16, 16), (0, 0, 0, 0))
        for y, r in enumerate(rows):
            for x, ch in enumerate(r):
                if ch in pal: im.putpixel((x, y), pal[ch] + (255,))
        im.save(f'{out}/{mat}_{tool}.png')
# preview sheet
sheet = Image.new('RGBA', (16 * 5 * 8 + 40, 16 * 2 * 8 + 30), (36, 34, 44, 255))
for j, mat in enumerate(PAL):
    for i, tool in enumerate(SHAPES):
        im = Image.open(f'{out}/{mat}_{tool}.png').resize((128, 128), Image.NEAREST)
        sheet.alpha_composite(im, (10 + i * 136, 10 + j * 138))
sheet.save(f'{out}/../tools_preview.png')
